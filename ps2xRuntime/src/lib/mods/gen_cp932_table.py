#!/usr/bin/env python3
"""Writes cp932_table.inc: the Unicode -> Windows-31J (code page 932, "Shift-JIS") table that fpr_save.cpp uses to turn the text of a
data pack into the bytes the game's save holds.

Why a table: the runtime must run on Windows, Linux, macOS and Android, and only Windows has a code page 932 converter in its system
libraries. The table is the public Microsoft code page (nothing from the game), taken from Python's own "cp932" codec so the C++ and the
Python tool (tools/fprsave.py) encode every character the same way, including the characters that code page 932 reaches by more than
one byte sequence (the codec's choice is the one recorded here).

Each entry is one 32-bit number: the Unicode code point in the top 16 bits and the code page 932 bytes in the bottom 16 (a single byte
is below 0x100). Entries are sorted by code point. U+0000 to U+007F map to themselves and are not listed.

    python -I gen_cp932_table.py [OUT]        (default: cp932_table.inc next to this script)
"""
import sys
from pathlib import Path

out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("cp932_table.inc")
entries = []
for u in range(0x80, 0x10000):
    if 0xD800 <= u <= 0xDFFF:
        continue
    try:
        b = chr(u).encode("cp932")
    except UnicodeEncodeError:
        continue
    entries.append((u << 16) | int.from_bytes(b, "big"))
lines = ["// Generated by gen_cp932_table.py from Python's cp932 codec: %d entries, (code point << 16) | code page 932 bytes." % len(entries),
         "// Do not edit. U+0000 to U+007F map to themselves and are not listed."]
for i in range(0, len(entries), 8):
    lines.append(" ".join("0x%08X," % e for e in entries[i:i + 8]))
out.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
print("wrote %s (%d entries)" % (out, len(entries)))
