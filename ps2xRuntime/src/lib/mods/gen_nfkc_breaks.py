#!/usr/bin/env python3
"""Writes nfkc_breaks.inc: the characters of code page 932 that make tools/fprsave.py show a name field as its raw text instead of its
ASCII-folded text, so fpr_save.cpp (fieldTextOrHex) decides the same way.

Why: fprsave.py's field_value tries NFKC(text) first and the decoded text second. NFKC turns full-width ASCII into ASCII, which is the
common case and easy to copy. But if ANY character of the field has a compatibility form that the page cannot write back to the same
bytes (the Roman numerals, circled digits, the (kabu) sign, the half-width katakana, the diaeresis...), the whole first try fails and
the field is shown unfolded: "Ａ¨Ｂ" stays full-width, "A¨B" would be wrong. This lists those characters, taken from Python's unicodedata,
so the C++ reader needs no Unicode database. Only the standard library; the answer does not depend on the Python version in any way that
has ever changed (compatibility decompositions are frozen by the Unicode stability policy).

    python -I gen_nfkc_breaks.py [OUT]        (default: nfkc_breaks.inc next to this script)
"""
import sys
import unicodedata
from pathlib import Path

out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).with_name("nfkc_breaks.inc")


def full_width(text):
    result = []
    for ch in text:
        c = ord(ch)
        if ch == " ":
            result.append("　")
        elif 0x21 <= c <= 0x7E:
            result.append(chr(c + 0xFEE0))
        else:
            result.append(ch)
    return "".join(result)


def folded(c):
    """What fpr_save.cpp's folding makes of a character: the same as NFKC for these, and nothing for the others."""
    if 0xFF01 <= c <= 0xFF5E:
        return c - 0xFEE0
    if c == 0x3000:
        return 0x20
    if c == 0xFFE0:
        return 0xA2
    if c == 0xFFE1:
        return 0xA3
    if c == 0xFFE2:
        return 0xAC
    return c


decodable = set()
breaks = set()
for u in range(0x80, 0x10000):
    if 0xD800 <= u <= 0xDFFF:
        continue
    try:
        data = chr(u).encode("cp932")
    except UnicodeEncodeError:
        continue
    shown = data.decode("cp932")  # the character the importer sees for these bytes
    decodable.add(ord(shown))
    for candidate in {chr(u), shown}:
        normal = unicodedata.normalize("NFKC", candidate)
        try:
            ok = full_width(normal).encode("cp932") == data
        except UnicodeEncodeError:
            ok = False
        if not ok:
            breaks.add(ord(candidate))
# Keep the ones the folding leaves alone (it cannot see that NFKC would change them), and the four marks it special-cases.
entries = sorted(c for c in breaks if c in decodable and (folded(c) == c or c in (0xFF9E, 0xFF9F, 0x309B, 0x309C)))
lines = ["// Generated by gen_nfkc_breaks.py from Python's unicodedata: %d characters. Do not edit." % len(entries),
         "// A text field holding any of these is not folded to ASCII (see fieldTextOrHex in fpr_save.cpp)."]
for i in range(0, len(entries), 12):
    lines.append(" ".join("0x%04X," % c for c in entries[i:i + 12]))
out.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
print("wrote %s (%d entries)" % (out, len(entries)))
